// Writes server/src/system_defaults.rs: every system-default tag label in the 4 locales, lowercased, per kind
// (src/lib/system-defaults.ts). Run after changing the Expenses.category/platform/payment messages:
//   node server/tools/system-defaults.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const keys = {
  category: ['groceries', 'dining', 'home', 'utilities', 'transport', 'health', 'leisure', 'shopping', 'pets', 'other'],
  platform: ['amazon', 'mercadolivre', 'shopee', 'loja_fisica'],
  payment: ['credit', 'debit', 'pix', 'cash'],
}
const locales = ['en', 'pt', 'es', 'fr'].map((l) => JSON.parse(readFileSync(`src/messages/${l}.json`, 'utf8')))
let out = '//! Generated by server/tools/system-defaults.mjs from src/messages/*.json — do not edit.\n\n'
for (const [kind, list] of Object.entries(keys)) {
  const labels = new Set()
  for (const m of locales) for (const k of list) { const label = m.Expenses?.[kind]?.[k]; if (label) labels.add(label.trim().toLowerCase()) }
  out += `pub const ${kind.toUpperCase()}: &[&str] = &${JSON.stringify([...labels].sort())};\n`
}
writeFileSync('server/src/system_defaults.rs', out)
console.log(out)
