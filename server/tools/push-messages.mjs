// Writes server/src/push_messages.rs: the Push namespace of src/messages/*.json (the text of each Web Push banner).
// Run after changing those messages:
//   node server/tools/push-messages.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const keys = ['EXPENSE_NEW', 'EXPENSE_NEW_RECURRING', 'PAYMENT_RECEIVED', 'DEBT_REMINDER', 'RECURRING_DUE', 'TEST', 'someone']
let out = '//! Generated by server/tools/push-messages.mjs from src/messages/*.json — do not edit.\n\n'
out += `pub const KEYS: [&str; ${keys.length}] = ${JSON.stringify(keys)};\n\n`
out += `/// (locale, messages in KEYS order)\npub const MESSAGES: [(&str, [&str; ${keys.length}]); 4] = [\n`
for (const locale of ['en', 'pt', 'es', 'fr']) {
  const push = JSON.parse(readFileSync(`src/messages/${locale}.json`, 'utf8')).Push
  out += `    (${JSON.stringify(locale)}, [${keys.map((k) => JSON.stringify(push[k])).join(', ')}]),\n`
}
out += '];\n'
writeFileSync('server/src/push_messages.rs', out)
console.log(out)
